/**
 * Find all profiles admitted to a specific school.
 */
export function findProfilesBySchool(school: string): AdmittedProfile[] {
  const normalized = school.toLowerCase().trim();
  return ADMITTED_PROFILES.filter(
    (p) => p.school.toLowerCase() === normalized
  );
}

/**
 * Find all profiles with a given hook status.
 * Valid values: "unhooked", "legacy", "URM", "first-gen", "recruited-athlete", "international"
 */
export function findProfilesByHookStatus(status: string): AdmittedProfile[] {
  const normalized = status.toLowerCase().trim();
  return ADMITTED_PROFILES.filter(
    (p) => p.hookStatus.toLowerCase() === normalized
  );
}

/**
 * Find profiles whose spike area matches keywords.
 * Searches both the spike field and activities array for keyword matches.
 */
export function findProfilesBySpikeArea(area: string): AdmittedProfile[] {
  const keywords = area
    .toLowerCase()
    .split(/\s+/)
    .filter((k) => k.length > 2);

  return ADMITTED_PROFILES.filter((p) => {
    const spikeText = p.spike.toLowerCase();
    const activitiesText = p.activities.join(" ").toLowerCase();
    const combined = `${spikeText} ${activitiesText}`;

    return keywords.some((keyword) => combined.includes(keyword));
  });
}

/**
 * Find profiles similar to a given student profile.
 * Matches on GPA range (+/- 0.15), SAT range (+/- 80), and spike keyword overlap.
 * Returns results sorted by relevance (most similar first).
 */
export function findSimilarProfiles(
  gpa: number,
  sat: number,
  spike: string
): AdmittedProfile[] {
  const spikeKeywords = spike
    .toLowerCase()
    .split(/\s+/)
    .filter((k) => k.length > 3);

  const scored = ADMITTED_PROFILES.map((p) => {
    let score = 0;

    // GPA proximity (0-3 points)
    const gpaDiff = Math.abs(p.gpa - gpa);
    if (gpaDiff <= 0.05) score += 3;
    else if (gpaDiff <= 0.10) score += 2;
    else if (gpaDiff <= 0.15) score += 1;

    // SAT proximity (0-3 points) — also check ACT converted
    const profileSat = p.sat || (p.act ? actToSat(p.act) : 0);
    if (profileSat > 0) {
      const satDiff = Math.abs(profileSat - sat);
      if (satDiff <= 20) score += 3;
      else if (satDiff <= 50) score += 2;
      else if (satDiff <= 80) score += 1;
    }

    // Spike keyword overlap (0-5 points)
    const profileSpike = `${p.spike} ${p.activities.join(" ")}`.toLowerCase();
    const matchCount = spikeKeywords.filter((k) =>
      profileSpike.includes(k)
    ).length;
    score += Math.min(matchCount, 5);

    return { profile: p, score };
  });

  return scored
    .filter((s) => s.score >= 2)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.profile);
}

/**
 * Rough ACT to SAT conversion for comparison purposes.
 */
function actToSat(act: number): number {
  const conversionTable: Record<number, number> = {
    36: 1590,
    35: 1570,
    34: 1550,
    33: 1520,
    32: 1490,
    31: 1460,
    30: 1430,
    29: 1400,
    28: 1370,
    27: 1340,
    26: 1310,
    25: 1280,
  };
  return conversionTable[act] || 1400;
}

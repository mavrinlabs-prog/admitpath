/**
 * Find a feeder school by name (case-insensitive partial match).
 */
export function findFeederSchool(query: string): FeederSchool | undefined {
  const q = query.toLowerCase();
  return FEEDER_SCHOOLS.find(
    (s) => s.name.toLowerCase().includes(q) || q.includes(s.name.toLowerCase())
  );
}

/**
 * Find all feeder schools in a given state.
 */
export function getFeederSchoolsByState(stateCode: string): FeederSchool[] {
  const code = stateCode.toUpperCase();
  return FEEDER_SCHOOLS.filter((s) => s.state === code);
}

/**
 * Find state admissions data by state name or code (case-insensitive).
 */
export function findStateAdmissions(query: string): StateAdmissions | undefined {
  const q = query.toLowerCase();
  return STATE_ADMISSIONS.find(
    (s) =>
      s.state.toLowerCase() === q ||
      s.stateCode.toLowerCase() === q
  );
}

/**
 * Get all schools that feed into a specific college (case-insensitive partial match).
 */
export function getSchoolsFeedingTo(collegeName: string): { school: FeederSchool; avgPerYear: number }[] {
  const q = collegeName.toLowerCase();
  const results: { school: FeederSchool; avgPerYear: number }[] = [];

  for (const school of FEEDER_SCHOOLS) {
    for (const placement of school.topPlacements) {
      if (placement.college.toLowerCase().includes(q)) {
        results.push({ school, avgPerYear: placement.avgPerYear });
      }
    }
  }

  return results.sort((a, b) => b.avgPerYear - a.avgPerYear);
}

/**
 * Get states sorted by competitiveness (using avg SAT as a proxy).
 */
export function getStatesByCompetitiveness(): StateAdmissions[] {
  return [...STATE_ADMISSIONS].sort((a, b) => b.avgSAT - a.avgSAT);
}

/**
 * Get states where students are underrepresented at a specific college.
 */
export function getUnderrepresentedStatesFor(collegeName: string): StateAdmissions[] {
  const q = collegeName.toLowerCase();
  return STATE_ADMISSIONS.filter((s) =>
    s.underrepresentedAt.some((c) => c.toLowerCase().includes(q))
  );
}

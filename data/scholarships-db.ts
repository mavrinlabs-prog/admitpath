/**
 * Parse a scholarship amount string into a comparable number.
 * Used for sorting by highest amount first.
 * "Full ride" / "Full tuition" / "Full cost of attendance" → 250,000
 * "$55,000/year" → 220,000 (x4)
 * "$20,000" → 20,000
 * "$1,000 - $50,000" → 50,000 (take max)
 * "$2,500 - $10,000+" → 10,000
 */
export function parseAmountForSort(amount: string): number {
  const lower = amount.toLowerCase();
  if (/full\s*(ride|cost|tuition|4.year|financial)/.test(lower)) return 250_000;

  // Find all dollar amounts in the string
  const matches = amount.match(/\$[\d,]+/g);
  if (!matches || matches.length === 0) return 0;

  const nums = matches.map((m) => parseInt(m.replace(/[$,]/g, ""), 10));
  let max = Math.max(...nums);

  // If per-year, multiply by 4
  if (/\/year|\/yr|per\s*year/i.test(amount)) {
    max *= 4;
  }

  return max;
}
